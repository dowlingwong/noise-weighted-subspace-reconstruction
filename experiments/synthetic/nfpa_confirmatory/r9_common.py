def prepare_output_dir(
    out_dir: Path,
    *,
    resume: bool,
    expected: dict[str, Any],
) -> dict[int, Path]:
    """Create or validate the output directory; return usable existing shards.

    A non-empty final output directory is refused outright unless ``--resume``
    was passed. On resume, the manifest must exist and agree with ``expected``
    on every provenance-critical field, and each shard is schema-validated
    before it is reused; anything that fails validation aborts the run rather
    than being silently recomputed or appended to.
    """
    out_dir = Path(out_dir)
    if not out_dir.exists():
        out_dir.mkdir(parents=True, exist_ok=True)
        return {}

    entries = [p for p in out_dir.iterdir() if not p.name.startswith(".")]
    if not entries:
        return {}

    if not resume:
        raise IntegrityError(
            f"output directory {out_dir} is not empty and --resume was not given; "
            f"refusing to overwrite {len(entries)} existing entries"
        )

    manifest_path = out_dir / "manifest.json"
    if not manifest_path.exists():
        raise IntegrityError(f"--resume requires {manifest_path}, which does not exist")
    manifest = json.loads(manifest_path.read_text())
    for key, want in expected.items():
        got = manifest.get(key)
        if got != want:
            raise IntegrityError(
                f"resume manifest mismatch for {key!r}: manifest has {got!r}, this run expects {want!r}"
            )
    return validate_existing_shards(out_dir, manifest)


def validate_existing_shards(out_dir: Path, manifest: dict) -> dict[int, Path]:
    """Validate every shard already on disk; return ``{seed: path}``."""
    columns = manifest.get("columns")
    cfg_hash = manifest.get("config_hash")
    regime = manifest.get("regime")
    methods = manifest.get("methods")
    found: dict[int, Path] = {}
    for shard in sorted(Path(out_dir).glob("seed_*.csv")):
        rows = read_rows_csv(shard)
        if not rows:
            raise IntegrityError(f"shard {shard} is empty")
        if columns is not None and list(rows[0].keys()) != list(columns):
            raise IntegrityError(f"shard {shard} has a schema that does not match the manifest")
        seeds = {int(r["seed"]) for r in rows}
        if len(seeds) != 1:
            raise IntegrityError(f"shard {shard} mixes seeds {sorted(seeds)}")
        seed = seeds.pop()
        if shard.name != f"seed_{seed:02d}.csv" and shard.name != f"seed_{seed}.csv":
            raise IntegrityError(f"shard {shard} does not match the seed {seed} it contains")
        if cfg_hash is not None and any(r.get("config_hash") != cfg_hash for r in rows):
            raise IntegrityError(f"shard {shard} has a config hash that differs from the manifest")
        if regime is not None and any(r.get("regime") not in (None, regime) for r in rows):
            raise IntegrityError(f"shard {shard} has an unexpected regime")
        if methods is not None and sorted({r["method"] for r in rows}) != sorted(methods):
            raise IntegrityError(
                f"shard {shard} method set {sorted({r['method'] for r in rows})} != manifest {sorted(methods)}"
            )
        found[seed] = shard
    return found


def shard_path(out_dir: Path, seed: int) -> Path:
    """Shard filename for a seed; two-digit for the scientific 0-29 range."""
    return Path(out_dir) / (f"seed_{seed:02d}.csv" if seed < 100 else f"seed_{seed}.csv")


