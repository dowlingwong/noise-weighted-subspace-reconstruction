def write_atomic_text(path: Path, text: str) -> None:
    """Write ``text`` to ``path`` via a temporary file and an atomic rename."""
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=str(path.parent), prefix=f".{path.name}.", suffix=".tmp")
    try:
        with os.fdopen(fd, "w", newline="") as handle:
            handle.write(text)
            handle.flush()
            os.fsync(handle.fileno())
        os.replace(tmp, path)
    except BaseException:
        if os.path.exists(tmp):
            os.unlink(tmp)
        raise


def _format_value(value: Any) -> str:
    """Deterministic CSV rendering; ``None`` becomes an empty field, never 0."""
    if value is None:
        return ""
    if isinstance(value, bool):
        return "True" if value else "False"
    if isinstance(value, (float, np.floating)):
        if not np.isfinite(value):
            return repr(float(value))
        return repr(float(value))
    if isinstance(value, (int, np.integer)):
        return str(int(value))
    return str(value)


def write_rows_csv(path: Path, rows: Sequence[dict], columns: Sequence[str]) -> None:
    """Write tidy rows atomically with a fixed column order."""
    import io

    buf = io.StringIO()
    writer = csv.DictWriter(buf, fieldnames=list(columns), extrasaction="raise", lineterminator="\n")
    writer.writeheader()
    for row in rows:
        missing = set(columns) - set(row)
        if missing:
            raise IntegrityError(f"row is missing columns {sorted(missing)}")
        writer.writerow({c: _format_value(row[c]) for c in columns})
    write_atomic_text(path, buf.getvalue())


def read_rows_csv(path: Path) -> list[dict[str, str]]:
    with Path(path).open(newline="") as handle:
        return list(csv.DictReader(handle))


def write_json(path: Path, payload: dict) -> None:
    """Write JSON atomically with sorted keys, so summaries are byte-stable."""
    write_atomic_text(path, json.dumps(payload, indent=2, sort_keys=True, allow_nan=True) + "\n")


def sha256_of(path: Path) -> str:
    h = hashlib.sha256()
    with Path(path).open("rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


