"""Shared output-safety contract for the Round 9 runners (E8, E9, E10).

Every Round 9 runner writes one atomic shard per seed *before* aggregation,
records full provenance in a manifest, and refuses to touch the archived
Block A directory. Aggregation is a deterministic function of the shards, so a
summary can be regenerated byte-for-byte from the raw seed files.

The safety rules implemented here come from
``docs/plans/rps2026/ROUND9_OVERNIGHT_REMOTE_RUNBOOK.md`` (Phase 2, "Shared
output contract"):

* an explicit output directory, never inferred from the Block A defaults;
* refusal to overwrite a non-empty final output directory without ``--resume``;
* validation of config hash, seed, regime, method set and schema on resume;
* temporary file plus atomic rename for every shard and summary;
* provenance: code commit, frozen config hash, interpreter and NumPy versions,
  hostname, thread limits, timestamps, wall time and the exact command;
* ``--smoke`` confined to ``results/rps2026/Round9_smoke/`` with synthetic
  seeds 900000/900001, which may never collide with the scientific seeds 0-29.

Nothing in this module makes a scientific choice. It decides only where bytes
are allowed to land and whether a resumed directory is trustworthy.
"""

from __future__ import annotations

import csv
import hashlib
import json
import os
import platform
import socket
