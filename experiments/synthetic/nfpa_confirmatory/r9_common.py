def concat_shards(paths: Iterable[Path]) -> list[dict[str, str]]:
    """Concatenate shards in ascending seed order, deterministically."""
    rows: list[dict[str, str]] = []
    for path in sorted(paths, key=lambda p: int(str(p.stem).split("_")[1])):
        rows.extend(read_rows_csv(path))
    return rows


def _as_float(value: str | float | None) -> float | None:
    if value is None or value == "":
        return None
    return float(value)


def bootstrap_paired(
    differences: Sequence[float],
    *,
    resamples: int = BOOTSTRAP_RESAMPLES,
    seed: int = BOOTSTRAP_SEED,
) -> dict[str, Any]:
    """Percentile bootstrap over *seed-level* paired differences.

    The resampling unit is the seed, never the event: each draw resamples the
    vector of per-seed differences with replacement. Returns the mean, the
    95% percentile interval, the fraction of seeds favouring a negative
    difference, and whether the interval excludes zero.
    """
    values = np.asarray([v for v in differences], dtype=float)
    if values.size == 0:
        raise IntegrityError("bootstrap requires at least one paired difference")
    if not np.all(np.isfinite(values)):
        raise IntegrityError("bootstrap input contains non-finite values")
    rng = np.random.default_rng(seed)
    idx = rng.integers(0, values.size, size=(int(resamples), values.size))
    means = values[idx].mean(axis=1)
    lo, hi = np.percentile(means, [2.5, 97.5])
    return {
        "n_seeds": int(values.size),
        "mean_difference": float(values.mean()),
        "ci95_low": float(lo),
        "ci95_high": float(hi),
        "excludes_zero": bool(lo > 0.0 or hi < 0.0),
        "fraction_negative": float(np.mean(values < 0.0)),
        "per_seed_differences": [float(v) for v in values],
        "bootstrap_resamples": int(resamples),
        "bootstrap_seed": int(seed),
        "resampling_unit": "seed",
    }


def paired_contrast(
    rows: Sequence[dict],
    *,
    metric: str,
    method_a: str,
    method_b: str,
    seed_key: str = "seed",
) -> dict[str, Any]:
    """Paired ``method_a - method_b`` contrast on ``metric``, one pair per seed."""
    by_seed: dict[int, dict[str, float | None]] = {}
    for row in rows:
        method = row["method"]
        if method not in (method_a, method_b):
            continue
        seed = int(row[seed_key])
        by_seed.setdefault(seed, {})[method] = _as_float(row.get(metric))
    diffs: list[float] = []
    seeds: list[int] = []
    for seed in sorted(by_seed):
        pair = by_seed[seed]
        if method_a not in pair or method_b not in pair:
            raise IntegrityError(f"seed {seed} is missing one of {method_a}/{method_b} for {metric}")
        a, b = pair[method_a], pair[method_b]
        if a is None or b is None:
            # A null metric is genuinely undefined for this method; it is not
            # zero and must not be contrasted.
            return {
                "metric": metric,
                "contrast": f"{method_a} - {method_b}",
                "identified": False,
                "reason": f"{metric} is undefined (null) for at least one method",
            }
        diffs.append(a - b)
        seeds.append(seed)
    out = bootstrap_paired(diffs)
    out.update(
        {
            "metric": metric,
            "contrast": f"{method_a} - {method_b}",
            "identified": True,
            "seeds": seeds,
            "sign_convention": (
                f"negative favours {method_a} (lower {metric} is better)"
            ),
        }
    )
    return out
