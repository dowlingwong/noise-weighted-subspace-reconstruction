#!/usr/bin/env python3
"""P1-E4b — the hyperparameter table, with a source path for every value.

Every number the manuscript's protocol sections quote should be traceable to
one file in this repository. This script reads the configuration files
themselves (never a transcription), flattens them, and emits

    results/paper1/P1-E4b/hyperparameters.tex   booktabs, one row per value
    results/paper1/P1-E4b/hyperparameters.csv   the same rows, machine-readable

with columns ``group | parameter | value | source``. Rows whose source file is
missing are still emitted, marked ``MISSING``, so a gap is visible rather than
silent.

Usage::

    python scripts/make_hyperparameter_table.py [--out results/paper1/P1-E4b]
"""

from __future__ import annotations

import argparse
import csv
import json
import platform
import time
from dataclasses import asdict
from pathlib import Path

import yaml

REPO_ROOT = Path(__file__).resolve().parents[1]

#: (group, path glob) in the order the table should read.
CONFIG_GROUPS: list[tuple[str, str]] = [
    ("Synthetic S0-S9", "configs/synthetic/*.yaml"),
    ("CRESST", "configs/cresst/cresst_validation.yaml"),
    ("GWOSC", "configs/gwosc/*.yaml"),
    ("TIDMAD", "configs/tidmad/phase*_real_noise.yaml"),
]

#: Keys that are prose, provenance or output plumbing rather than protocol.
SKIP_KEYS = {"output", "citation", "source_url", "notes", "contract"}


def _flatten(obj, prefix: str = "") -> list[tuple[str, str]]:
    out: list[tuple[str, str]] = []
    if isinstance(obj, dict):
        for k, v in obj.items():
            if k in SKIP_KEYS:
                continue
            out.extend(_flatten(v, f"{prefix}{k}."))
    elif isinstance(obj, list):
        if all(not isinstance(x, (dict, list)) for x in obj):
            out.append((prefix.rstrip("."), json.dumps(obj)))
        else:
            for i, v in enumerate(obj):
                out.extend(_flatten(v, f"{prefix}{i}."))
    else:
        out.append((prefix.rstrip("."), "" if obj is None else str(obj)))
    return out


def planted_generator_rows() -> list[dict]:
    """The frozen NFPA `PrimaryConfig`, read from the dataclass itself."""
    import sys

    sys.path.insert(0, str(REPO_ROOT))
    from experiments.synthetic.nfpa_confirmatory.config import PRIMARY, config_hash

    src = "experiments/synthetic/nfpa_confirmatory/config.py"
    rows = [{"group": "Planted generator (NFPA)", "parameter": k, "value": str(v), "source": src}
            for k, v in asdict(PRIMARY).items()]
    rows.append({"group": "Planted generator (NFPA)", "parameter": "config_hash",
                 "value": config_hash(PRIMARY), "source": src})
    rows.append({"group": "Planted generator (NFPA)", "parameter": "derived.d = C*T",
                 "value": str(PRIMARY.C * PRIMARY.T), "source": src})
    rows.append({"group": "Planted generator (NFPA)", "parameter": "derived.rank = k_c*k_t",
                 "value": str(PRIMARY.k_c * PRIMARY.k_t), "source": src})
    return rows


def config_rows() -> list[dict]:
    rows: list[dict] = []
    for group, pattern in CONFIG_GROUPS:
        paths = sorted(REPO_ROOT.glob(pattern))
        if not paths:
            rows.append({"group": group, "parameter": pattern, "value": "",
                         "source": f"{pattern} (MISSING)"})
            continue
        for path in paths:
            rel = str(path.relative_to(REPO_ROOT))
            data = yaml.safe_load(path.read_text()) or {}
            for key, value in _flatten(data):
                rows.append({"group": group, "parameter": f"{path.stem}.{key}",
                             "value": value, "source": rel})
    return rows


def _tex_escape(s: str) -> str:
    for a, b in (("\\", r"\textbackslash{}"), ("_", r"\_"), ("%", r"\%"), ("&", r"\&"),
                 ("#", r"\#"), ("$", r"\$"), ("{", r"\{"), ("}", r"\}"), ("^", r"\^{}"),
                 ("~", r"\textasciitilde{}")):
        s = s.replace(a, b)
    return s


def write_tex(rows: list[dict], path: Path) -> None:
    lines = [
        "% Generated by scripts/make_hyperparameter_table.py -- do not edit by hand.",
        "% Every row's `source' column is a path in the experiment repository.",
        r"\begin{longtable}{p{0.20\linewidth} p{0.30\linewidth} p{0.20\linewidth} p{0.24\linewidth}}",
        r"\caption{Frozen hyperparameters, with the repository path each value is read from.}",
        r"\label{tab:hyperparameters}\\",
        r"\toprule",
        r"Group & Parameter & Value & Source \\",
        r"\midrule",
        r"\endfirsthead",
        r"\toprule",
        r"Group & Parameter & Value & Source \\",
        r"\midrule",
        r"\endhead",
    ]
    last_group = None
    for r in rows:
        group = "" if r["group"] == last_group else _tex_escape(r["group"])
        last_group = r["group"]
        value = r["value"]
        if len(value) > 60:
            value = value[:57] + "..."
        lines.append(f"{group} & \\texttt{{{_tex_escape(r['parameter'])}}} & "
                     f"\\texttt{{{_tex_escape(value)}}} & \\texttt{{{_tex_escape(r['source'])}}} \\\\")
    lines += [r"\bottomrule", r"\end{longtable}", ""]
    path.write_text("\n".join(lines))


def main(argv=None) -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", type=str, default="results/paper1/P1-E4b")
    a = ap.parse_args(argv)
    out = REPO_ROOT / a.out
    out.mkdir(parents=True, exist_ok=True)

    rows = planted_generator_rows() + config_rows()

    missing = [r for r in rows if "(MISSING)" in r["source"]
               or not (REPO_ROOT / r["source"].split(" ")[0]).exists()]
    for r in missing:
        r["source"] = r["source"].split(" ")[0] + " (MISSING)"

    with (out / "hyperparameters.csv").open("w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=["group", "parameter", "value", "source"])
        w.writeheader()
        w.writerows(rows)
    write_tex(rows, out / "hyperparameters.tex")

    sources = sorted({r["source"] for r in rows})
    summary = {
        "n_rows": len(rows),
        "n_sources": len(sources),
        "sources": sources,
        "n_missing_sources": len(missing),
        "missing_sources": sorted({r["source"] for r in missing}),
        "all_sources_exist": not missing,
        "generated_utc": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        "host": platform.node(),
    }
    (out / "summary.json").write_text(json.dumps(summary, indent=2))

    # Manifest, so every A-priority card carries one (ground rule 4).
    import sys
    sys.path.insert(0, str(REPO_ROOT))
    from experiments.paper1 import common
    from experiments.synthetic.nfpa_confirmatory.config import PRIMARY
    common.write_manifest(out, experiment_id="P1-E4b", cfgs=[PRIMARY], seeds=[],
                          extra={"n_rows": len(rows), "n_sources": len(sources),
                                 "all_sources_exist": not missing,
                                 "walltime_s": 0.0, "host": platform.node(),
                                 "platform": platform.platform()})
    print(f"{len(rows)} rows from {len(sources)} sources -> {out}")
    if missing:
        print(f"WARNING: {len(missing)} rows have a missing source file")


if __name__ == "__main__":
    main()
