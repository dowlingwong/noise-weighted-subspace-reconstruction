def _git(*args: str) -> str:
    try:
        return subprocess.run(
            ["git", *args], cwd=str(REPO_ROOT), capture_output=True, text=True, timeout=60, check=True
        ).stdout.strip()
    except Exception:  # pragma: no cover - provenance must never crash a run
        return "unavailable"


def provenance(command: Sequence[str], cfg: PrimaryConfig) -> dict:
    """Collect the provenance block embedded in every Round 9 manifest."""
    head = _git("rev-parse", "HEAD")
    dirty = _git("status", "--porcelain")
    return {
        "implementation_freeze_commit": head,
        "code_commit": head,
        "git_tree_dirty": bool(dirty) if dirty != "unavailable" else None,
        "config_hash": config_hash(cfg),
        "primary_config_hash": PRIMARY_HASH,
        "config": asdict(cfg),
        "python_version": sys.version.split()[0],
        "python_executable": sys.executable,
        "numpy_version": np.__version__,
        "platform": platform.platform(),
        "hostname": socket.gethostname(),
        "thread_limits": {
            key: os.environ.get(key)
            for key in ("OPENBLAS_NUM_THREADS", "OMP_NUM_THREADS", "MKL_NUM_THREADS", "NUMEXPR_NUM_THREADS")
        },
        "command": list(command),
    }


