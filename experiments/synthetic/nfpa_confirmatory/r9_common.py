import sys
import tempfile
from dataclasses import asdict
from pathlib import Path
from typing import Any, Iterable, Sequence

import numpy as np

from .config import PRIMARY, PRIMARY_HASH, PrimaryConfig, config_hash

REPO_ROOT = Path(__file__).resolve().parents[3]
RESULTS_ROOT = REPO_ROOT / "results" / "rps2026"

#: The archived Block A directory. No Round 9 runner may resolve into it.
ARCHIVED_E1_DIR = RESULTS_ROOT / "E1_nfpa_blockA"
ARCHIVED_E1_CSV = ARCHIVED_E1_DIR / "block_A_colored_raw.csv"

#: Smoke output is confined below this directory.
SMOKE_ROOT = RESULTS_ROOT / "Round9_smoke"

#: Synthetic smoke seeds. Deliberately far from the scientific seeds 0-29.
SMOKE_SEEDS = (900000, 900001)

#: The five registered methods. ``PCA`` is not a valid name.
REGISTERED_METHODS = ("CW-PCA", "NFPA", "Iso-MPCA", "IsoPCA", "OF")

#: Frozen bootstrap settings for every Round 9 paired contrast.
BOOTSTRAP_RESAMPLES = 10_000
BOOTSTRAP_SEED = 20260819

#: Relative tolerance for reproducing an archived fit. Never loosened.
REPRODUCTION_RTOL = 1e-9


class IntegrityError(RuntimeError):
    """Raised when an output-safety or provenance gate fails."""


# --------------------------------------------------------------------------
# Output directory guards
# --------------------------------------------------------------------------


def _is_within(child: Path, parent: Path) -> bool:
    """True when ``child`` is ``parent`` or lies underneath it, after resolution."""
    child = child.resolve()
    parent = parent.resolve()
    return child == parent or parent in child.parents


def resolve_out_dir(out_dir: str | os.PathLike[str], *, smoke: bool) -> Path:
    """Resolve, validate and return the output directory.

    Rejects any path that is equal to, inside, or symlink-resolving into the
    archived Block A directory, and confines smoke output below
    ``results/rps2026/Round9_smoke/``.
    """
    path = Path(out_dir).expanduser()
    if not path.is_absolute():
        path = (Path.cwd() / path).resolve()
    # ``resolve`` follows symlinks for existing components, which is exactly the
    # check we want: a symlinked output directory must not land in the archive.
    resolved = path.resolve()

    if _is_within(resolved, ARCHIVED_E1_DIR):
        raise IntegrityError(
            f"output directory {resolved} resolves into the archived Block A directory "
            f"{ARCHIVED_E1_DIR}; the archive is read-only"
        )
    if smoke and not _is_within(resolved, SMOKE_ROOT):
        raise IntegrityError(
            f"--smoke output must live below {SMOKE_ROOT}, got {resolved}"
        )
    if not smoke and _is_within(resolved, SMOKE_ROOT):
        raise IntegrityError(
            f"non-smoke output must not be written below the smoke root {SMOKE_ROOT}"
        )
    return resolved


def guard_seed_set(
    seeds: Sequence[int],
    expected: Sequence[int],
    *,
    smoke: bool,
    allow_subset: bool = False,
) -> list[int]:
    """Validate a requested seed set against the frozen expectation.

    With ``--smoke`` the only permitted seeds are :data:`SMOKE_SEEDS`. Otherwise
    the seed set must equal ``expected`` exactly, unless ``allow_subset`` is set
    (used only by the one-seed reproduction gate, which writes no results).
    """
    seeds = [int(s) for s in seeds]
    if len(set(seeds)) != len(seeds):
        raise IntegrityError(f"duplicate seeds requested: {seeds}")
    if smoke:
        if sorted(seeds) != sorted(SMOKE_SEEDS):
            raise IntegrityError(f"--smoke requires seeds {list(SMOKE_SEEDS)}, got {seeds}")
        return sorted(seeds)
    if any(s in SMOKE_SEEDS for s in seeds):
        raise IntegrityError("smoke seeds may not be used without --smoke")
    expected_sorted = sorted(int(s) for s in expected)
    if allow_subset:
        extra = sorted(set(seeds) - set(expected_sorted))
        if extra:
            raise IntegrityError(f"seeds {extra} are outside the registered set {expected_sorted}")
        return sorted(seeds)
    if sorted(seeds) != expected_sorted:
        raise IntegrityError(
            f"unexpected seed set: got {sorted(seeds)}, registered set is {expected_sorted}"
        )
    return sorted(seeds)


def smoke_config(base: PrimaryConfig = PRIMARY) -> PrimaryConfig:
    """A reduced fixture for ``--smoke`` built with :func:`dataclasses.replace`.

    The frozen ``PRIMARY`` object is never mutated; the smoke configuration has
    its own hash, so a smoke shard can never be mistaken for a scientific one.
    """
    from dataclasses import replace

    return replace(
        base,
        C=6,
        T=32,
        N_train=60,
        N_validation=30,
        N_test=80,
        N_calibration=64,
        n_restarts=2,
        n_als_iter=8,
        bootstrap_resamples=200,
    )


